// Touchline fan app: one match, one cue stream, a different broadcast for every viewer.
import { CrewRoom } from "./crewroom.js";
import { Graphics } from "./graphics.js";
import { HALF, airTime, loadBroadcast, loadMatch } from "./match.js";
import { Pitch } from "./pitch.js";

const $ = (s) => document.querySelector(s);
const qs = new URLSearchParams(location.search);
const store = {
  get(k, d) { try { return localStorage.getItem(`tl-${k}`) ?? d; } catch { return d; } },
  set(k, v) { try { localStorage.setItem(`tl-${k}`, v); } catch { /* private mode */ } },
};

const PERSONA_HINT = {
  analyst: "Numbers first: xG, pass difficulty and why each pass was hard, the control index, pressing.",
  casual: "The story and the feeling, in plain words. Fewer numbers, bigger moments.",
  studio: "Clean broadcast captions, the way a studio would put them on air.",
};
const PRESET = { analyst: { camera: "tactical", metric: "pass_difficulty" }, casual: { camera: "broadcast", metric: "" }, studio: { camera: "broadcast", metric: "" } };

const view = {
  persona: store.get("persona", "casual"), lang: store.get("lang", "en"), club: "", player: "", metric: "",
  camera: "broadcast", speed: Number(store.get("speed", 2)), source: "recorded",
};
let M, pitch, gfx, crew, cues = [], ptr = 0, T = 0, playing = false, last = performance.now(), activeTags = [], ws = null;

async function pickMatch() {
  const list = await fetch("/api/matches").then((r) => r.json());
  $("#loading").hidden = true;
  $("#picker").hidden = false;
  $("#list").innerHTML = list.map((m) => `
    <button class="fixture" data-id="${m.match_id}">
      <span class="teams"><i style="background:${m.kits.home.primary}"></i>${m.home} <span style="color:var(--dim)">v</span> <i style="background:${m.kits.away.primary}"></i>${m.away}</span>
      <span class="score">${m.final.home}-${m.final.away}</span>
      <span class="sub">${m.venue} · ${m.match_id}${m.broadcast ? ' · <span class="badge">recorded crew broadcast</span>' : ""}</span>
    </button>`).join("");
  $("#list").onclick = (e) => {
    const b = e.target.closest(".fixture");
    if (b) location.search = `?match=${b.dataset.id}`;
  };
}

function segment(id, value, onPick) {
  const el = $(id);
  const mark = (v) => el.querySelectorAll("button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.v === String(v))));
  mark(value);
  el.onclick = (e) => {
    const b = e.target.closest("button");
    if (!b) return;
    mark(b.dataset.v);
    onPick(b.dataset.v);
  };
  return mark;
}

function slotOf(pid, ms) {
  for (let s = 0; s < 22; s++) if (M.playerAt(s, ms) === pid) return s;
  return null;
}

function applyPersona(p, preset = true) {
  view.persona = p;
  store.set("persona", p);
  $("#persona-hint").textContent = PERSONA_HINT[p];
  if (preset) {
    setCamera(PRESET[p].camera);
    if (!view.player || PRESET[p].metric) setMetric(PRESET[p].metric);
  }
  gfx.set({ persona: p, showSources: true });
}

let markCamera, markSpeed, markSource;
function setCamera(c) { view.camera = c; pitch.mode = c; markCamera?.(c); }
function setMetric(m) { view.metric = m; $("#metric").value = m; $("#spark").hidden = !m; gfx.set({ metric: m }); }

function buildRail() {
  const md = M.meta;
  segment("#persona", view.persona, (v) => applyPersona(v));
  const clubs = [["", "Neutral"], ["home", md.home.short], ["away", md.away.short]];
  $("#club").innerHTML = clubs.map(([v, n]) => `<button data-v="${v}">${n}</button>`).join("");
  segment("#club", view.club, (v) => { view.club = v; fillPlayers(); gfx.set({ team: v || null }); });
  fillPlayers();
  $("#player").onchange = (e) => {
    view.player = e.target.value;
    gfx.set({ player: view.player || null });
    if (view.player && view.camera === "broadcast" && view.persona !== "studio") setCamera("player");
    if (!view.player && view.camera === "player") setCamera("broadcast");
    focusPanel(true);
  };
  $("#metric").onchange = (e) => setMetric(e.target.value);
  segment("#lang", view.lang, (v) => { view.lang = v; store.set("lang", v); gfx.set({ lang: v }); });
  markCamera = segment("#camera", view.camera, (v) => setCamera(v));
  markSpeed = segment("#speed", view.speed, (v) => { view.speed = Number(v); store.set("speed", v); if (view.source === "live") goLive(); });
  markSource = segment("#source", view.source, (v) => (v === "live" ? goLive() : goRecorded()));
  $("#toggle-rail").onclick = () => document.body.classList.toggle("rail-closed");
  $("#about").innerHTML = `${md.venue} · ${md.weather} · ${md.referee}<br>Every club, player and event here is generated by the Touchline match engine. Lines marked <b style="color:var(--ok)">verified</b> were checked against the event log before they aired.`;
}

function fillPlayers() {
  const md = M.meta, sides = view.club ? [view.club] : ["home", "away"];
  const opts = sides.flatMap((s) => md[s].players.map((p) => ({ ...p, side: s }))).sort((a, b) => (a.side === b.side ? a.number - b.number : a.side < b.side ? 1 : -1));
  $("#player").innerHTML = `<option value="">Nobody in particular</option>` +
    opts.map((p) => `<option value="${p.id}">${p.number} · ${p.name} · ${md[p.side].short} · ${p.role}</option>`).join("");
  $("#player").value = view.player && opts.some((p) => p.id === view.player) ? view.player : "";
}

// ---------- player focus: the line from the log, distance and speed from tracking ----------
let focusCache = { pid: null, upTo: 0, dist: 0, top: 0, last: null };
function physical(pid, ms) {
  if (focusCache.pid !== pid || ms < focusCache.upTo) focusCache = { pid, upTo: 0, dist: 0, top: 0, last: null };
  const hz = M.hz, total = M.nFrames[0] + M.nFrames[1];
  const f0 = Math.floor((M.frameAt(focusCache.upTo) ?? M.nFrames[0])), f1 = Math.floor(M.frameAt(ms) ?? M.nFrames[0]);
  for (let f = f0; f < Math.min(f1, total - 1); f++) {
    const t = f < M.nFrames[0] ? f / hz : HALF + (f - M.nFrames[0]) / hz;
    const s = slotOf(pid, t);
    if (s === null) { focusCache.last = null; continue; }
    const x = M.frames[f * 48 + s * 2] / M.scale, y = M.frames[f * 48 + s * 2 + 1] / M.scale;
    if (focusCache.last && focusCache.last.s === s && f !== M.nFrames[0]) {
      const d = Math.hypot(x - focusCache.last.x, y - focusCache.last.y);
      if (d < 1.2) { focusCache.dist += d; focusCache.speed = d * hz * 3.6; focusCache.top = Math.max(focusCache.top, Math.min(focusCache.speed, 37)); }
    }
    focusCache.last = { s, x, y };
  }
  focusCache.upTo = ms;
  return focusCache;
}

let lastFocus = 0;
function focusPanel(force = false) {
  const el = $("#focus");
  if (!view.player) { el.hidden = true; return; }
  if (!force && performance.now() - lastFocus < 700) return;
  lastFocus = performance.now();
  const p = M.players[view.player], L = M.line(view.player, T), ph = physical(view.player, T);
  const row = (k, v) => `<div class="row"><span>${k}</span><b>${v}</b></div>`;
  const onPitch = slotOf(view.player, T) !== null;
  el.hidden = false;
  el.innerHTML = `<div class="who">${p.name}</div><div class="role">#${p.number} · ${p.role} · ${M.meta[p.team].name}${onPitch ? "" : " · on the bench"}</div>
    ${row("Passes", `${L.complete}/${L.passes}${L.passes ? ` · ${Math.round((100 * L.complete) / L.passes)}%` : ""}`)}
    ${row(view.persona === "casual" ? "Shots" : "Shots · xG", view.persona === "casual" ? L.shots : `${L.shots} · ${L.xg.toFixed(2)}`)}
    ${row("Goals", L.goals)}${row("Tackles won", L.tackles)}
    ${row("Distance", `${(ph.dist / 1000).toFixed(1)} km`)}${row("Top speed", `${ph.top.toFixed(1)} km/h`)}`;
}

// ---------- the metric sparkline ----------
let sparkAt = 0;
function spark() {
  if (!view.metric || performance.now() - sparkAt < 900) return;
  sparkAt = performance.now();
  const c = $("#spark"), g = c.getContext("2d"), W = c.width, H = c.height;
  g.clearRect(0, 0, W, H);
  g.font = "22px IBM Plex Mono, monospace";
  g.fillStyle = "#7f8a83";
  const series = [];
  let label = "";
  if (view.metric === "xg") {
    for (const side of ["home", "away"]) {
      let acc = 0; const pts = [[0, 0]];
      for (const e of M.events) { if (e.ms > T) break; if (e.type === "shot" && e.team === side) { acc += e.q.xg; pts.push([e.ms, acc]); } }
      pts.push([T, acc]);
      series.push({ pts, color: M.meta[side].kit.primary, end: acc });
    }
    label = `xG ${series[0].end.toFixed(2)} · ${series[1].end.toFixed(2)}`;
  } else if (view.metric === "pass_difficulty") {
    const passes = cues.filter((c2) => c2.kind === "pass_card" && airTime(c2) <= T).slice(-14);
    series.push({ bars: passes.map((p) => p.payload.difficulty), color: "#f2b84b" });
    label = passes.length ? `hardest completed passes · last ${Math.round(passes.at(-1).payload.difficulty * 100)}` : "hard passes appear here";
  } else if (view.metric === "speed") {
    label = view.player ? `${M.short(view.player)} · now ${(focusCache.speed || 0).toFixed(1)} km/h · top ${focusCache.top.toFixed(1)}` : "pick a player to follow";
    series.push({ bars: [Math.min(1, (focusCache.speed || 0) / 36), Math.min(1, focusCache.top / 36)], color: "#7cc6ff" });
  }
  const top = 30, h = H - top - 6;
  for (const s of series) {
    if (s.pts) {
      const maxY = Math.max(1, ...series.map((q) => q.end)) * 1.1, maxX = Math.max(T, 600);
      g.strokeStyle = s.color; g.lineWidth = 4; g.beginPath();
      s.pts.forEach(([x, y], i) => { const px = (x / maxX) * W, py = top + h - (y / maxY) * h; i ? g.lineTo(px, py) : g.moveTo(px, py); });
      g.stroke();
    } else if (s.bars) {
      const bw = W / Math.max(s.bars.length, 1);
      s.bars.forEach((v, i) => { g.fillStyle = s.color; g.fillRect(i * bw + 3, top + h - v * h, bw - 6, v * h); });
    }
  }
  g.fillStyle = "#b9bfb6";
  g.fillText(label, 0, 22);
}

// ---------- the cue timeline ----------
function seek(ms, quiet = true) {
  T = Math.max(0, Math.min(ms, M.end));
  gfx.clear();
  activeTags = [];
  lastBig = { match_s: -1, priority: 0 };
  ptr = cues.findIndex((c) => airTime(c) > T);
  if (ptr < 0) ptr = cues.length;
  // Restore the latest momentum state so the screen is right straight after a jump.
  const mom = cues.slice(0, ptr).filter((c) => c.kind === "momentum").at(-1);
  if (mom) gfx.show(mom);
  gfx.clock(M.clock(T), M.scoreAt(T));
  pitch.prev = null;
  focusPanel(true);
}

function advance(dt) {
  if (playing && view.source === "recorded") {
    T += dt * view.speed;
    if (T > M.len[0] && T < HALF) {
      // The interval: hold for a moment so the half-time recap can be read, then restart.
      if (!advance.held) { advance.held = performance.now(); T = M.len[0] + 0.01; }
      else if (performance.now() - advance.held > 9000) { T = HALF; advance.held = 0; }
      else T = M.len[0] + 0.01;
    }
    if (T >= M.end) { T = M.end; playing = false; $("#play").textContent = "▶"; }
  }
  while (view.source === "recorded" && ptr < cues.length && airTime(cues[ptr]) <= T) air(cues[ptr++]);
}

let lastBig = { match_s: -1, priority: 0 };
function air(cue) {
  // A slower line about an earlier, smaller moment yields to a bigger moment that already aired.
  if (cue.kind === "line" || cue.kind === "insight") {
    if (cue.priority >= 3) lastBig = { match_s: cue.match_s, priority: cue.priority };
    else if (cue.match_s < lastBig.match_s && T - lastBig.match_s < 30) return;
  }
  if (cue.kind === "player_tag") {
    if (gfx.wants(cue)) activeTags.push({ cue, until: performance.now() + (cue.ttl_s || 4) * 1000 });
    return;
  }
  gfx.show(cue);
}

// ---------- tags projected from the pitch ----------
const tagEls = new Map();
function drawTags(state) {
  const layer = $("#tags"), now = performance.now(), keep = new Set();
  activeTags = activeTags.filter((t) => t.until > now);
  const want = [];
  for (const t of activeTags) {
    const s = slotOf(t.cue.audience.player, T);
    if (s !== null) want.push({ key: t.cue.id, slot: s, html: tagHtml(t.cue), color: M.meta[s < 11 ? "home" : "away"].kit.primary });
  }
  if (view.player) {
    const s = slotOf(view.player, T);
    if (s !== null) want.push({ key: "focus", slot: s, cls: "focus", html: `${M.players[view.player].number} ${M.short(view.player)}`, color: M.meta[s < 11 ? "home" : "away"].kit.primary });
  }
  if (view.persona !== "analyst" && state) {
    let best = null, bd = 2.2;
    for (let s = 0; s < 22; s++) { const d = Math.hypot(state.positions[s * 2] - state.x, state.positions[s * 2 + 1] - state.y); if (d < bd) { bd = d; best = s; } }
    if (best !== null && !want.some((w) => w.slot === best)) {
      const pid = M.playerAt(best, T);
      want.push({ key: "carrier", slot: best, html: M.short(pid), color: M.meta[best < 11 ? "home" : "away"].kit.primary });
    }
  }
  const pt = {};
  for (const w of want) {
    if (!state) break;
    const x = state.positions[w.slot * 2], y = state.positions[w.slot * 2 + 1];
    pitch.project(x, y, 2.4, pt);
    if (!pt.visible) continue;
    let el = tagEls.get(w.key);
    if (!el) { el = document.createElement("div"); el.className = `tag ${w.cls || ""}`; layer.appendChild(el); tagEls.set(w.key, el); }
    const html = `<i style="background:${w.color}"></i>${w.html}`;
    if (el._html !== html) { el.innerHTML = html; el._html = html; }
    el.style.left = `${pt.x}px`; el.style.top = `${pt.y}px`;
    keep.add(w.key);
  }
  for (const [k, el] of tagEls) if (!keep.has(k)) { el.remove(); tagEls.delete(k); }
}

function tagHtml(cue) {
  const p = cue.payload;
  if (cue.audience.metric === "speed") return `${p.number} ${p.player} <span class="v">${p.speed_kmh} km/h</span>`;
  if (cue.audience.metric === "distance") return `${p.number} ${p.player} <span class="v">${p.distance_km} km</span>`;
  return `${p.player}`;
}

// ---------- live mode: the server runs the match and the crew, pushing cues as they air ----------
function goRecorded() {
  view.source = "recorded";
  markSource?.("recorded");
  if (ws) { ws.close(); ws = null; }
  crew.reset();
  seek(T);
}

function goLive() {
  view.source = "live";
  markSource?.("live");
  if (ws) ws.close();
  gfx.clear();
  crew.reset();
  const proto = location.protocol === "https:" ? "wss" : "ws";
  ws = new WebSocket(`${proto}://${location.host}/ws/live/${M.meta.match_id}?speed=${view.speed}&start=${Math.floor(T)}`);
  ws.onmessage = (ev) => {
    const msg = JSON.parse(ev.data);
    if (msg.type === "hello") {
      (msg.recent || []).filter((c) => c.kind === "momentum").slice(-1).forEach((c) => gfx.show(c));
      (msg.recent || []).forEach((c) => crew.push(c));
    }
    else if (msg.type === "clock") { T = msg.match_s; gfx.clock(M.clock(T), msg.score); }
    else if (msg.type === "cue") { crew.push(msg.cue); air(msg.cue); }
    else if (msg.type === "end") { goRecorded(); }
  };
  ws.onclose = () => { if (view.source === "live") { view.source = "recorded"; markSource?.("recorded"); } };
  playing = true;
  $("#play").textContent = "❚❚";
}

// ---------- the loop ----------
function frame(now) {
  const dt = Math.min((now - last) / 1000, 0.1);
  last = now;
  if (view.source === "live" && playing) T += dt * view.speed;     // smooth between server clocks
  advance(dt);
  if (view.source === "recorded") crew.sync(cues, ptr);
  pitch.period = T < HALF ? 1 : 2;
  pitch.resize();
  const focus = view.player ? slotOf(view.player, T) : null;
  const st = pitch.update(T, focus, dt);
  $("#interval").hidden = !!st;
  pitch.render();
  drawTags(st);
  gfx.clock(M.clock(T));
  $("#time").textContent = M.clock(T);
  if (document.activeElement !== $("#seek")) $("#seek").value = String(T);
  focusPanel();
  spark();
  requestAnimationFrame(frame);
}

async function main() {
  const id = qs.get("match");
  if (!id) return pickMatch();
  M = await loadMatch(id);
  cues = (await loadBroadcast(id)).sort((a, b) => airTime(a) - airTime(b));
  document.title = `${M.meta.home.short} v ${M.meta.away.short} · Touchline`;
  pitch = new Pitch($("#pitch"), M);
  gfx = new Graphics($("#gfx"), M.meta, { persona: view.persona, lang: view.lang });
  buildRail();
  applyPersona(view.persona);
  crew = new CrewRoom($("#crewroom"), M);
  $("#toggle-crew").onclick = () => { crew.toggle(); store.set("crew", crew.visible ? "1" : "0"); };
  if ((qs.get("crew") ?? store.get("crew", "0")) === "1") crew.toggle(true);
  $("#seek").max = String(M.end);
  $("#marks").innerHTML = M.goals.map((g) => `<i style="left:${(100 * g.ms) / M.end}%;background:${M.meta[g.team].kit.primary}" title="${M.name(g.player)} ${M.clock(g.ms)}"></i>`).join("");
  $("#seek").oninput = (e) => { if (view.source === "live") goRecorded(); seek(Number(e.target.value)); };
  $("#play").onclick = () => { playing = !playing; $("#play").textContent = playing ? "❚❚" : "▶"; };
  document.addEventListener("keydown", (e) => {
    if (e.target.tagName === "SELECT" || e.target.tagName === "INPUT") return;
    if (e.code === "KeyC") $("#toggle-crew").click();
    if (e.code === "Space") { e.preventDefault(); $("#play").click(); }
    if (e.code === "ArrowRight") seek(T + 15);
    if (e.code === "ArrowLeft") seek(T - 15);
  });
  const start = Number(qs.get("t") || 0);
  seek(start);
  if (!cues.length) $("#source").querySelector('[data-v="recorded"]').textContent = "Replay";
  $("#loading").hidden = true;
  if (qs.get("autoplay") !== "0") { playing = true; $("#play").textContent = "❚❚"; }
  requestAnimationFrame(frame);
}

main().catch((e) => { $("#loading").textContent = `Could not load the match: ${e.message}`; });
