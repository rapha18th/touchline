"""Measure dial vectors on Kaggle CPU kernels.

Each kernel is one self-contained script. The engine source rides inside it as a base64 zip and
a job list names the dial vectors and the seeds, so nothing mounts and nothing downloads. The
kernel plays every (vector, seed) match across its cores and writes one small result.json,
which is pulled with --file-pattern into a temp folder, never into the repo.

    python engine/tools/kaggle_eval.py '{"SHOT_VALUE": 0.7}' --seeds 1-24
"""

from __future__ import annotations

import base64
import io
import json
import os
import re
import subprocess
import sys
import tempfile
import threading
import time
import uuid
import zipfile
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1] / "touchline_engine"
USER = os.environ.get("KAGGLE_USER", "thetraveller")
SLOTS = [f"touchline-calib-{c}" for c in "abcd"]
WORK = Path(tempfile.gettempdir()) / "touchline-kaggle"
ENV = {**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8"}

KERNEL = r'''
"""Touchline realism sweep: {label}. Generated by engine/tools/kaggle_eval.py."""
import base64, io, json, os, sys, time, zipfile
from multiprocessing import Pool

TOKEN = "{token}"
BLOB = "{blob}"
JOBS = json.loads(r"""{jobs}""")
SEEDS = {seeds}

root = "/tmp/tl"
zipfile.ZipFile(io.BytesIO(base64.b64decode(BLOB))).extractall(root)
sys.path.insert(0, root)
from touchline_engine import realism, sim  # noqa: E402


def one(task):
    j, seed = task
    sim.set_dials(JOBS[j]["dials"])
    t0 = time.time()
    m = sim.Match(seed).play()
    row = {{"seed": seed, **realism.measure(m)}}
    row["secs"] = round(time.time() - t0, 1)
    return j, row


if __name__ == "__main__":
    t0 = time.time()
    tasks = [(j, s) for s in SEEDS for j in range(len(JOBS))]
    out = {{j: [] for j in range(len(JOBS))}}
    cores = os.cpu_count()
    print("cores", cores, "tasks", len(tasks), flush=True)
    with Pool(cores) as pool:
        for k, (j, row) in enumerate(pool.imap_unordered(one, tasks), 1):
            out[j].append(row)
            print(k, "/", len(tasks), "job", j, "seed", row["seed"], row["secs"], "s", flush=True)
    results = []
    for j, job in enumerate(JOBS):
        rows = sorted(out[j], key=lambda r: r["seed"])
        rep = realism.summarise(rows)
        results.append({{"id": job["id"], "dials": job["dials"], "summary": rep["summary"],
                        "score": realism.score(rep), "rows": rows}})
    os.makedirs("/kaggle/working", exist_ok=True)
    with open("/kaggle/working/result.json", "w") as f:
        json.dump({{"token": TOKEN, "cores": cores, "wall_s": round(time.time() - t0, 1),
                   "seeds": SEEDS, "results": results}}, f)
    print("done", round(time.time() - t0, 1), "s", flush=True)
'''


def engine_blob(extra: tuple[Path, ...] = ()) -> str:
    """The engine package, plus any extra top-level modules, as a base64 zip."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(ENGINE.glob("*.py")):
            z.write(p, f"touchline_engine/{p.name}")
        for p in extra:
            z.write(p, p.name)
    return base64.b64encode(buf.getvalue()).decode()


def parse_seeds(text: str) -> list[int]:
    out: list[int] = []
    for part in text.split(","):
        if "-" in part:
            a, b = part.split("-")
            out += list(range(int(a), int(b) + 1))
        elif part:
            out.append(int(part))
    return out


def _run(args: list[str], timeout: int = 180) -> str:
    try:
        p = subprocess.run(["kaggle", *args], capture_output=True, text=True, timeout=timeout, env=ENV,
                           encoding="utf-8", errors="replace")
        return (p.stdout or "") + (p.stderr or "")
    except subprocess.TimeoutExpired:
        return "timeout"


def build(slot: str, script: str) -> Path:
    d = WORK / slot
    d.mkdir(parents=True, exist_ok=True)
    (d / "sweep.py").write_text(script, encoding="utf-8")
    meta = {"id": f"{USER}/{slot}", "title": slot, "code_file": "sweep.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": False,
            "enable_internet": False, "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
            "model_sources": []}
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    return d


def render_sweep(jobs: list[dict], seeds: list[int], label: str):
    """A renderer for the realism sweep: token -> script text."""
    blob = engine_blob()
    return lambda token: KERNEL.format(label=label, token=token, blob=blob, jobs=json.dumps(jobs), seeds=json.dumps(seeds))


def status(slot: str) -> str:
    out = _run(["kernels", "status", f"{USER}/{slot}"], timeout=90)
    m = re.search(r'status "?(?:KernelWorkerStatus\.)?(\w+)', out)
    return m.group(1).upper() if m else "UNKNOWN:" + out.strip()[-120:]


def pull(slot: str, token: str) -> dict | None:
    dest = WORK / "out" / slot
    dest.mkdir(parents=True, exist_ok=True)
    f = dest / "result.json"
    if f.exists():
        f.unlink()
    _run(["kernels", "output", f"{USER}/{slot}", "-p", str(dest), "--file-pattern", r"result\.json", "-o"], timeout=300)
    if not f.exists():
        return None
    data = json.loads(f.read_text(encoding="utf-8"))
    return data if data.get("token") == token else None


def run_script(slot: str, render, label: str, log=print, max_wait_s: int = 5400) -> dict:
    """Push one kernel rendered from render(token), wait, pull its result.json. Raises when it fails twice."""
    for attempt in (1, 2):
        token = uuid.uuid4().hex[:12]
        d = build(slot, render(token))
        while True:
            out = _run(["kernels", "push", "-p", str(d)], timeout=300)
            if "successfully pushed" in out.lower() or "kernel version" in out.lower():
                break
            if "maximum batch cpu session" in out.lower() or "timeout" in out.lower():
                log(f"{slot}: waiting for a free CPU session ({out.strip()[-80:]})")
                time.sleep(90)
                continue
            raise RuntimeError(f"{slot}: push failed: {out.strip()[-300:]}")
        log(f"{slot}: pushed {label}, attempt {attempt}")
        t0 = time.time()
        time.sleep(60)
        while time.time() - t0 < max_wait_s:
            st = status(slot)
            if st == "COMPLETE":
                data = pull(slot, token)
                if data is not None:
                    log(f"{slot}: complete in {data['wall_s']} s on {data['cores']} cores")
                    return data
                if time.time() - t0 > 240:
                    log(f"{slot}: complete but the result is missing or stale")
                    break
            elif st in ("ERROR", "CANCELACKNOWLEDGED", "CANCELREQUESTED"):
                log(f"{slot}: status {st}")
                break
            time.sleep(45)
        else:
            log(f"{slot}: timed out after {max_wait_s} s")
    raise RuntimeError(f"{slot}: no result for {label}")


def run_many(tasks: list[tuple], slots: list[str] | None = None, log=print) -> list[dict | None]:
    """Run (render, label) tasks across the kernel slots, one kernel per slot at a time; results in order."""
    slots = slots or SLOTS
    results: dict[int, dict] = {}
    errors: list[str] = []
    lock = threading.Lock()
    queue = list(enumerate(tasks))

    def worker(slot: str):
        while True:
            with lock:
                if not queue:
                    return
                k, (render, label) = queue.pop(0)
            try:
                data = run_script(slot, render, label, log=log)
                data["kernel"] = slot
                with lock:
                    results[k] = data
            except Exception as e:  # noqa: BLE001
                with lock:
                    errors.append(str(e))

    threads = [threading.Thread(target=worker, args=(s,)) for s in slots[:max(1, min(len(slots), len(tasks)))]]
    for t in threads:
        t.start()
        time.sleep(5)
    for t in threads:
        t.join()
    if errors:
        log("kernel errors: " + " | ".join(errors))
    return [results.get(k) for k in range(len(tasks))]


def measure(vectors: list[dict], seeds: list[int], per_kernel: int = 2, slots: list[str] | None = None,
            label: str = "sweep", log=print) -> list[dict | None]:
    """Measure full dial vectors; returns one result per vector, in order, across concurrent kernels."""
    jobs = [{"id": i, "dials": v} for i, v in enumerate(vectors)]
    chunks = [jobs[i:i + per_kernel] for i in range(0, len(jobs), per_kernel)]
    tasks = [(render_sweep(c, seeds, f"{label} part {k}"), f"{label} part {k} ({len(c)} vectors x {len(seeds)} seeds)")
             for k, c in enumerate(chunks)]
    results: dict[int, dict] = {}
    for data in run_many(tasks, slots, log):
        if data is None:
            continue
        for r in data["results"]:
            r["cores"], r["wall_s"], r["kernel"] = data["cores"], data["wall_s"], data["kernel"]
            results[r["id"]] = r
    return [results.get(i) for i in range(len(vectors))]

if __name__ == "__main__":
    import argparse

    sys.path.insert(0, str(ENGINE.parent))
    from touchline_engine import realism, sim

    ap = argparse.ArgumentParser()
    ap.add_argument("dials", nargs="*", help="JSON dial overrides, one vector per argument")
    ap.add_argument("--seeds", default="1-24")
    ap.add_argument("--per-kernel", type=int, default=2)
    ap.add_argument("--out", default=None, help="write the results as JSON here")
    a = ap.parse_args()
    base = sim.dials()
    vecs = [{**base, **json.loads(d)} for d in (a.dials or ["{}"])]
    res = measure(vecs, parse_seeds(a.seeds), per_kernel=a.per_kernel)
    for v, r in zip(vecs, res):
        if r is None:
            print("no result for", v)
            continue
        print(json.dumps({k: v[k] for k in v if v[k] != base[k]}))
        print(realism.table({"matches": len(r["rows"]), "summary": r["summary"]}))
    if a.out:
        Path(a.out).write_text(json.dumps(res), encoding="utf-8")
