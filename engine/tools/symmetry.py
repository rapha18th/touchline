"""Side-bias check: play each fixture twice with the clubs swapped and compare by side.

With home advantage worth only a small strength bump, xG for the home side and the away
side should come out close; a large gap points to a geometry bug in one direction.

    python engine/tools/symmetry.py --n 24 --kaggle --out reports/symmetry.json   # 48 matches on Kaggle
    python engine/tools/symmetry.py --n 2 --workers 2                              # local smoke check
"""

import argparse
import json
import math
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from touchline_engine.sim import Match  # noqa: E402
from touchline_engine.squads import make_fixture  # noqa: E402

KERNEL = r'''
"""Touchline side-bias check: {label}. Generated by engine/tools/symmetry.py."""
import base64, io, json, os, sys, time, zipfile
from multiprocessing import Pool

TOKEN = "{token}"
BLOB = "{blob}"
SEEDS = {seeds}
root = "/tmp/tl"
zipfile.ZipFile(io.BytesIO(base64.b64decode(BLOB))).extractall(root)
sys.path.insert(0, root)
from symmetry import one  # noqa: E402

if __name__ == "__main__":
    t0 = time.time()
    with Pool(os.cpu_count()) as pool:
        res = pool.map(one, SEEDS)
    os.makedirs("/kaggle/working", exist_ok=True)
    with open("/kaggle/working/result.json", "w") as f:
        json.dump({{"token": TOKEN, "cores": os.cpu_count(), "wall_s": round(time.time() - t0, 1),
                   "seeds": SEEDS, "pairs": res}}, f)
    print("done", round(time.time() - t0, 1), "s", flush=True)
'''


def side_stats(m: Match) -> list[tuple[float, int, int]]:
    out = []
    for t in (0, 1):
        tid = m.teams[t].id
        shots = [e for e in m.events if e["type"] == "shot" and e["team"] == tid]
        out.append((sum(e["q"]["xg"] for e in shots), len(shots), m.score[t]))
    return out


def one(seed: int):
    a, b = make_fixture(seed)
    normal = side_stats(Match(seed, a, b).play())
    a, b = make_fixture(seed)
    a.id, b.id = "away", "home"
    for p in a.players:
        p.id = "away" + p.id[4:]
    for p in b.players:
        p.id = "home" + p.id[4:]
    swapped = side_stats(Match(seed, b, a).play())
    return normal, swapped


def aggregate(seeds: list[int], res: list) -> dict:
    """Per-match home minus away xG, with its standard error, over both legs of every fixture."""
    diffs, home, away = [], [], []
    for normal, swapped in res:
        for leg in (normal, swapped):
            home.append(leg[0])
            away.append(leg[1])
            diffs.append(leg[0][0] - leg[1][0])
    m = len(diffs)
    mean_d = sum(diffs) / m
    sd = math.sqrt(sum((d - mean_d) ** 2 for d in diffs) / max(m - 1, 1))

    def avg(rows, i):
        return round(sum(r[i] for r in rows) / m, 3)

    return {"matches": m, "seeds": seeds,
            "home": {"xg": avg(home, 0), "shots": avg(home, 1), "goals": avg(home, 2)},
            "away": {"xg": avg(away, 0), "shots": avg(away, 1), "goals": avg(away, 2)},
            "xg_gap_home_minus_away": round(mean_d, 3), "xg_gap_se": round(sd / math.sqrt(m), 3),
            "gap_in_standard_errors": round(mean_d / max(sd / math.sqrt(m), 1e-9), 2)}


def run_kaggle(seeds: list[int], parts: int) -> list:
    import kaggle_eval
    me = Path(__file__).resolve()
    blob = kaggle_eval.engine_blob(extra=(me,))
    chunks = [seeds[i::parts] for i in range(parts)]

    def render(k: int, c: list[int]):
        return lambda token: KERNEL.format(label=f"part {k}", token=token, blob=blob, seeds=json.dumps(c))

    tasks = [(render(k, c), f"symmetry part {k} ({len(c)} fixtures x 2)") for k, c in enumerate(chunks)]
    out = kaggle_eval.run_many(tasks)
    if any(d is None for d in out):
        raise SystemExit("a symmetry kernel failed")
    pairs = {}
    for d in out:
        pairs.update(zip(d["seeds"], d["pairs"]))
    return [pairs[s] for s in seeds]


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=12, help="fixtures; each is played twice")
    ap.add_argument("--start", type=int, default=1)
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--kaggle", action="store_true", help="play on Kaggle CPU kernels instead of this machine")
    ap.add_argument("--parts", type=int, default=4, help="kernels to split the fixtures over with --kaggle")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    seeds = list(range(a.start, a.start + a.n))
    if a.kaggle:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        res = run_kaggle(seeds, a.parts)
    else:
        with ProcessPoolExecutor(a.workers) as ex:
            res = list(ex.map(one, seeds))
    rep = aggregate(seeds, res)
    h, w = rep["home"], rep["away"]
    print(f"{rep['matches']} matches  home xG {h['xg']:.2f} shots {h['shots']:.1f} goals {h['goals']:.2f}  |  "
          f"away xG {w['xg']:.2f} shots {w['shots']:.1f} goals {w['goals']:.2f}  |  "
          f"gap {rep['xg_gap_home_minus_away']:+.3f} xG per match ({rep['gap_in_standard_errors']:+.2f} SE)")
    if a.out:
        Path(a.out).write_text(json.dumps(rep, indent=1), encoding="utf-8")
